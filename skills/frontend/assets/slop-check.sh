#!/usr/bin/env bash
# slop-check.sh: static scan of a frontend for the tells that make it read as
# AI generated. Run it in the critique loop (Step 8) and before every deploy.
#
#   bash slop-check.sh [src-dir] [--strict]
#
# FAIL lines are not negotiable and set exit code 1. WARN lines are judgment
# calls: each one is either fixed or has a reason you can say out loud.
# --strict turns every WARN into a FAIL. The catalogue behind each check is
# references/slop-audit.md.
#
# Works with GNU grep (Linux, Git Bash) and BSD grep (macOS).

set -u
export LC_ALL=C   # byte-level matching: emoji and dash patterns work in any locale
DIR="${1:-}"
STRICT=0
for a in "$@"; do [ "$a" = "--strict" ] && STRICT=1; done
if [ -z "$DIR" ] || [ "$DIR" = "--strict" ]; then
  for d in src app components; do [ -d "$d" ] && DIR="$d" && break; done
fi
[ -d "${DIR:-}" ] || { echo "usage: bash slop-check.sh [src-dir] [--strict]"; exit 2; }

UI=(--include=*.tsx --include=*.jsx --include=*.mdx --include=*.html --include=*.vue --include=*.svelte --include=*.astro)
CODE=("${UI[@]}" --include=*.ts --include=*.js --include=*.json)
STYLE=(--include=*.css --include=*.scss)
EXCL=(--exclude-dir=node_modules --exclude-dir=.next --exclude-dir=dist --exclude-dir=out --exclude-dir=.vercel --exclude-dir=ui)

fails=0
warns=0

# hits <grep flags...> <pattern> : prints matching lines (file:line:text)
hits() { grep -rnI "${EXCL[@]}" "$@" "$DIR" 2>/dev/null | sed "s#^${DIR%/}/##"; }

report() { # level, title, matches, fix
  local level="$1" title="$2" matches="$3" fix="$4"
  local n
  n=$(printf '%s' "$matches" | grep -c . || true)
  [ "$n" -eq 0 ] && return
  if [ "$level" = WARN ] && [ "$STRICT" -eq 1 ]; then level=FAIL; fi
  if [ "$level" = FAIL ]; then fails=$((fails + 1)); else warns=$((warns + 1)); fi
  printf '%-4s %s (%s)\n' "$level" "$title" "$n"
  printf '%s\n' "$matches" | head -3 | cut -c1-150 | sed 's/^/       /'
  printf '       fix: %s\n' "$fix"
}

threshold() { # level, title, matches, max, fix : reports only when count > max
  local n
  n=$(printf '%s' "$3" | grep -c . || true)
  [ "$n" -gt "$4" ] && report "$1" "$2 [over $4]" "$3" "$5"
}

echo "slop-check: $DIR"
echo

# ── Copy ──────────────────────────────────────────────────────────────────────
report FAIL "Em dash in product text" \
  "$(hits "${CODE[@]}" -e $'\xe2\x80\x94')" \
  "comma, colon, period or parentheses. references/ui-copy.md"

report FAIL "Generated-copy vocabulary" \
  "$(hits "${UI[@]}" -iE "seamless(ly)?|effortless(ly)?|empower(s|ing)?|unlock (the (power|potential|full)|new (levels|possibilities)|your (full|true) potential)|revolutioni[sz]e|supercharge|next[- ]gen(eration)?|cutting[- ]edge|game[- ]?chang|in today'?s (fast|digital)|harness the power|elevate your|streamline your|unleash|reimagined|the future of [a-z]+ is here")" \
  "say what the product does, in words a person would say out loud"

report FAIL "Placeholder content" \
  "$(hits "${CODE[@]}" -iE "lorem ipsum|dolor sit amet|test user ?[0-9]|asdf|foo@bar|john doe|jane doe|example@example")" \
  "seed data is copy: plausible names, amounts and dates from the domain"

report FAIL "Default framework metadata" \
  "$(hits "${CODE[@]}" -iE "Create Next App|Generated by create next app|Vite \+ React|React App</title>")" \
  "set the title, description and og:image in the root layout"

report WARN "Vague call to action" \
  "$(hits "${UI[@]}" -E ">[[:space:]]*(Get [Ss]tarted|Learn [Mm]ore|Sign [Uu]p [Nn]ow|Click [Hh]ere|Submit|Read [Mm]ore)[[:space:]]*<")" \
  "verb plus object: Open the app, Run a test payroll, Read the docs"

report WARN "Exclamation mark in UI text" \
  "$(hits "${UI[@]}" -E ">[^<{}]*[a-z]![[:space:]]*<")" \
  "be more specific instead of louder"

report WARN "Fabricated social proof" \
  "$(hits "${UI[@]}" -iE "trusted by|loved by|testimonial|5[- ]star|★★★★★|10,000\+ (users|teams)|join (thousands|millions)")" \
  "only real logos, real quotes and numbers you measured, each linked to proof"

report WARN "Unverified metric" \
  "$(hits "${UI[@]}" -E ">[^<{]*([0-9]+x (faster|cheaper|better)|99\.9+%|[^0-9.]100%)")" \
  "keep it only if you measured it and can show where"

report WARN "Emoji in UI" \
  "$(hits "${UI[@]}" -e $'\xf0\x9f')" \
  "one icon set, drawn at one stroke width, or nothing"

# ── Color and gradients ───────────────────────────────────────────────────────
report FAIL "Gradient text" \
  "$(hits "${UI[@]}" "${STYLE[@]}" -E "bg-clip-text|background-clip:[[:space:]]*text")" \
  "solid text. let weight, size and space carry the headline"

report FAIL "Raw Tailwind palette class (renders nothing with the token reset)" \
  "$(hits "${UI[@]}" -E "\b(bg|text|from|via|to|border|ring|fill|stroke|outline|decoration|divide|shadow)-(slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-[0-9]{2,3}\b")" \
  "use a token: bg-surface, text-fg-mute, border-line, bg-accent-soft"

report WARN "The AI palette (purple, violet, indigo, fuchsia)" \
  "$(hits "${UI[@]}" "${STYLE[@]}" -iE "purple|violet|indigo|fuchsia|#(8b5cf6|7c3aed|6d28d9|a855f7|9333ea|6366f1|4f46e5|818cf8|c084fc|d946ef)\b")" \
  "fine only if it is the brand and carries meaning; never as a default gradient"

threshold WARN "Gradients outside the atmosphere field" \
  "$(hits "${UI[@]}" "${STYLE[@]}" -E "bg-(linear|gradient)-to-|linear-gradient\(|radial-gradient\(|conic-gradient\(" | grep -v "globals.css:")" 3 \
  "gradients live in .field atmosphere only, mixed from the --field tokens"

threshold WARN "Raw hex colors outside the token block" \
  "$(hits "${UI[@]}" -E "#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b" | grep -v "href=\"#")" 8 \
  "a color that is not a token is a color nobody decided on"

# ── Surfaces, corners, elevation ──────────────────────────────────────────────
report WARN "Default shadow scale (removed by the token reset)" \
  "$(hits "${UI[@]}" -E "\bshadow-(sm|md|lg|xl|2xl|inner)\b")" \
  "shadow-card, shadow-pop or shadow-frame, and only on things that float"

report WARN "Default radius scale instead of component radius" \
  "$(hits "${UI[@]}" -E "\brounded-(sm|md|lg|xl|2xl|3xl)\b")" \
  "rounded-button, -input, -tile, -panel, -feature, -chip"

threshold WARN "Glass everywhere" \
  "$(hits "${UI[@]}" "${STYLE[@]}" -E "backdrop-blur|backdrop-filter")" 3 \
  "blur the floating nav and one overlay; the rest is solid"

threshold WARN "Everything centered" \
  "$(hits "${UI[@]}" -E "\btext-center\b")" 12 \
  "center the hero and the thesis; left-align the rest to the container edge"

threshold WARN "Bold everywhere" \
  "$(hits "${UI[@]}" -E "\bfont-(bold|extrabold|black)\b")" 6 \
  "weight is hierarchy. two or three weights for the whole site"

threshold WARN "Tiny text" \
  "$(hits "${UI[@]}" -E "text-\[(8|9|10|11)px\]|\btext-xs\b")" 12 \
  "12px is the floor for anything a person must read; labels only below that"

# ── Motion ────────────────────────────────────────────────────────────────────
motion_used=$(hits "${UI[@]}" "${STYLE[@]}" -lE "@keyframes|animate-|transition|motion\.|useAnimate|whileInView|data-reveal" | head -1)
reduced=$(hits "${UI[@]}" "${STYLE[@]}" -lE "prefers-reduced-motion|useReducedMotion|motion-reduce" | head -1)
if [ -n "$motion_used" ] && [ -z "$reduced" ]; then
  report FAIL "Motion without a reduced-motion path" "$motion_used" \
    "add the prefers-reduced-motion block (globals.css has one)"
fi

report WARN "Attention-seeking animation" \
  "$(hits "${UI[@]}" -E "animate-(bounce|ping|wiggle)|repeat:[[:space:]]*Infinity" )" \
  "loops belong to the one signature element, paused offscreen"

threshold WARN "transition-all" \
  "$(hits "${UI[@]}" "${STYLE[@]}" -E "transition-all|transition:[[:space:]]*all")" 2 \
  "name the properties: transform, opacity, colors"

# ── Structure and accessibility ───────────────────────────────────────────────
report WARN "Clickable div" \
  "$(hits "${UI[@]}" -E "<(div|span)[^>]*onClick")" \
  "a <button> or a link. keyboards and screen readers cannot use a div"

report WARN "Image without alt" \
  "$(hits "${UI[@]}" -E "<(img|Image)[[:space:]][^>]*>" | grep -v "alt=")" \
  "describe it, or alt=\"\" if it is decorative"

report FAIL "Hotlinked image" \
  "$(hits "${UI[@]}" "${STYLE[@]}" -E "src=[\"']https?://|url\([\"']?https?://" | grep -viE "fonts\.(googleapis|gstatic)")" \
  "put it in /public and commit it"

icons=$(hits "${CODE[@]}" -ohE "from [\"'](lucide-react|@heroicons/react[^\"']*|react-icons[^\"']*|@fortawesome[^\"']*|@tabler/icons-react|@phosphor-icons/react|@radix-ui/react-icons)[\"']" | sed -E "s/from [\"']//; s/[\"']$//; s#/.*##" | sort -u)
nicons=$(printf '%s' "$icons" | grep -c . || true)
[ "$nicons" -gt 1 ] && report WARN "More than one icon library" "$icons" "pick one set, one stroke width"

fonts=$(hits "${CODE[@]}" -ohE "import \{[^}]+\} from [\"']next/font/google[\"']" | sed -E 's/import \{([^}]*)\}.*/\1/' | tr ',' '\n' | sed 's/ //g' | grep . | sort -u)
nfonts=$(printf '%s' "$fonts" | grep -c . || true)
[ "$nfonts" -gt 3 ] && report WARN "More than three font families" "$fonts" "one family, plus mono and an optional display face"

echo
if [ "$fails" -eq 0 ] && [ "$warns" -eq 0 ]; then
  echo "clean: no tells found. Now look at the screenshots; this script cannot see."
elif [ "$fails" -eq 0 ]; then
  echo "$warns warning(s), 0 failures. Fix each warning or say why it stays."
else
  echo "$fails failure(s), $warns warning(s)."
fi
[ "$fails" -eq 0 ]
